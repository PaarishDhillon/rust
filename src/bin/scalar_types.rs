fn main(){
    // signed integers
    let i0: i8 = 1;
    let i1: i16 = 1;
    let i2: i32 = 1;
    let i3: i64 = 1;
    let i4: i128 = 1;
    let i5: isize = 1;
    println!("{i0}");
    println!("{i1}");
    println!("{i2}");
    println!("{i3}");
    println!("{i4}");
    println!("{i5}");
    // unsigned integrers
    let u0: u8 = 1;
    let u1: u16 = 1;
    let u2: u32 = 1;
    let u3: u64 = 1;
    let u4: u128 = 1;
    let u5: usize = 1;
    println!("{u0}");
    println!("{u1}");
    println!("{u2}");
    println!("{u3}");
    println!("{u4}");
    println!("{u5}");
    // floats
    let f0:f32 = 0.01;
    let f1:f64 = 0.01;
    println!("{f0}");
    println!("{f1}");
    // bool
    let b: bool  = true;
    println!("{b}");
    // character
    let c: char = 'c';
    let e: char = 'e';
    println!("{c}");
    println!("{e}");
}